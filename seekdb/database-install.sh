#!/usr/bin/env bash
# Install seekdb (https://github.com/oceanbase/seekdb, OceanBase's
# MySQL-compatible database) and size it for this node.
#
# Usage: database-install.sh [--version 1.4.0] [--memory-pct 60]
#
#   --version     seekdb release (a v<version> tag on GitHub; default 1.4.0)
#   --memory-pct  seekdb's memory budget as a share of RAM (default 60, the
#                 same share MySQL gets for its buffer pool: HammerDB runs on
#                 the same node)
#
# Installs the release's .deb for the closest supported Debian or Ubuntu
# version, writes /etc/seekdb/seekdb.cnf before the first start (seekdb takes
# the port, CPU count and memory only when it initializes its data directory),
# and runs it as seekdb.service. seekdb listens on every address and has no
# setting to change that, and root has no password until this script sets
# one, so parmaham-seekdb-firewall.service (started before seekdb, also at
# boot) drops connections to its ports from anywhere but the loopback
# interface. Clients connect over TCP to 127.0.0.1 (port SEEKDB_PORT, default
# 2881): seekdb has no Unix socket.
#
# Re-running keeps an initialized server: change the memory budget with
# ALTER SYSTEM, or remove /var/lib/seekdb to initialize again.
source "$(dirname "$0")/../common/lib.sh"

usage() { sed -n '2,23p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

require_root
load_config
while (($#)); do
    case $1 in
        --version)    conf_set SEEKDB_VERSION "$2"; shift 2 ;;
        --memory-pct) conf_set SEEKDB_MEMORY_PCT "$2"; shift 2 ;;
        -h|--help)    usage ;;
        *) warn "unknown option $1"; usage 1 ;;
    esac
done
load_db
[[ $(os_family) == debian ]] || die "the seekdb installer supports Debian and Ubuntu only for now"

SERVICE=$(db_service)
claim_database seekdb
install_payload
base_packages
# the MySQL command line client (seekdb has none of its own)
command -v mysql &>/dev/null || pkg_install mysql-client

# ---------------------------------------------------------------------------
# 1. Package
# ---------------------------------------------------------------------------
if ! command -v seekdb &>/dev/null; then
    # shellcheck disable=SC1091
    . /etc/os-release
    arch=$(dpkg --print-architecture)
    assets=$(curl -fsSL "https://api.github.com/repos/oceanbase/seekdb/releases/tags/v$SEEKDB_VERSION" \
        | python3 -c 'import json,sys; [print(a["browser_download_url"]) for a in json.load(sys.stdin)["assets"]]') \
        || die "seekdb release v$SEEKDB_VERSION not found on GitHub"
    # this OS version's package, else the newest one of the same distribution
    # (seekdb only depends on libaio and systemd)
    # (no match is not an error here: grep's status must not stop the script)
    url=$(grep -E "${ID}${VERSION_ID}_${arch}\.deb$" <<< "$assets" | head -1 || true)
    [[ -n $url ]] || url=$(grep -E "${ID}[0-9.]+_${arch}\.deb$" <<< "$assets" | sort -V | tail -1 || true)
    [[ -n $url ]] || die "no seekdb $SEEKDB_VERSION package for $ID $arch"
    log "installing $(basename "$url")"
    curl -fsSL -o /tmp/seekdb.deb "$url"
    pkg_install /tmp/seekdb.deb
    rm -f /tmp/seekdb.deb
    # the package starts nothing; configuration first
    systemctl stop "$SERVICE" 2>/dev/null || true
else
    log "seekdb is already installed: $(dpkg-query -W -f '${Version}' seekdb)"
fi

# ---------------------------------------------------------------------------
# 2. Firewall: seekdb's ports only from this node
# ---------------------------------------------------------------------------
command -v nft &>/dev/null || pkg_install nftables
# the empty table and the delete make reloading the file idempotent
cat > "$PMH_ETC/seekdb-firewall.nft" <<EOF
# Generated by Parma Ham seekdb/database-install.sh: seekdb's SQL and RPC
# ports from the loopback interface only
table inet parmaham_seekdb {}
delete table inet parmaham_seekdb
table inet parmaham_seekdb {
  chain input {
    type filter hook input priority 0; policy accept;
    iifname != "lo" tcp dport { $SEEKDB_PORT, $((SEEKDB_PORT + 1)) } drop
  }
}
EOF
cat > /etc/systemd/system/parmaham-seekdb-firewall.service <<EOF
[Unit]
Description=Parma Ham: seekdb ports from the loopback interface only
Before=$SERVICE.service network-pre.target
Wants=network-pre.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/nft -f $PMH_ETC/seekdb-firewall.nft
ExecStop=/usr/sbin/nft delete table inet parmaham_seekdb

[Install]
WantedBy=multi-user.target
RequiredBy=$SERVICE.service
EOF
systemctl daemon-reload
systemctl enable --now parmaham-seekdb-firewall.service &>/dev/null \
    || die "could not install the firewall for seekdb's ports"

# ---------------------------------------------------------------------------
# 3. Configuration (applied when the data directory is initialized)
# ---------------------------------------------------------------------------
MEM_MB=$(mem_total_mb)
CPUS=$(cpu_count)
BUDGET_MB=$(( MEM_MB * SEEKDB_MEMORY_PCT / 100 ))
FRESH_INSTALL=0
if [[ ! -d /var/lib/seekdb/store ]]; then
    FRESH_INSTALL=1
    log "writing /etc/seekdb/seekdb.cnf (RAM ${MEM_MB}MB, ${CPUS} CPUs, memory budget ${BUDGET_MB}MB)"
    cat > /etc/seekdb/seekdb.cnf <<EOF
# Generated by Parma Ham database-install.sh on $(date -u '+%F %T') UTC.
# These parameters are permanently valid
base-dir=/var/lib/seekdb
data-dir=/var/lib/seekdb/store
redo-dir=/var/lib/seekdb/store/redo

# These parameters are valid only during initialization
port=$SEEKDB_PORT
cpu_count=$CPUS
memory_budget=${BUDGET_MB}M
EOF
fi

install_os_tuning "$SERVICE"
systemctl enable "$SERVICE" &>/dev/null
systemctl restart "$SERVICE"
log "waiting for seekdb (the first start initializes the data directory)"
for i in $(seq 1 120); do
    if mysql -h127.0.0.1 -P"$SEEKDB_PORT" -uroot -e 'SELECT 1' &>/dev/null \
        || { [[ -r $MYSQL_ADMIN_CNF ]] && mysql_admin -e 'SELECT 1' &>/dev/null; }; then break; fi
    sleep 5
done

# root starts without a password; give it one, as for MySQL
if [[ ! -r $MYSQL_ADMIN_CNF ]]; then
    ROOT_PASS=$(random_password)
    mysql -h127.0.0.1 -P"$SEEKDB_PORT" -uroot -e "ALTER USER root IDENTIFIED BY '$ROOT_PASS'" \
        || die "seekdb did not start (journalctl -u $SERVICE, /var/lib/seekdb/log)"
    write_client_cnf "$MYSQL_ADMIN_CNF" root "$ROOT_PASS" root 0600
    [[ -e /root/.my.cnf ]] || ln -s "$MYSQL_ADMIN_CNF" /root/.my.cnf
fi
db_wait
# UTC timestamps (seekdb defaults to +08:00), as on the other databases
db_admin "SET GLOBAL time_zone = '+00:00'"
# seekdb ends any statement after 10 s by default (ob_query_timeout); MySQL
# has no such limit, and HammerDB's statistics step and the purge's CALL take
# longer. Global variables apply to new sessions only, so this comes before
# anything else connects.
db_admin "SET GLOBAL ob_query_timeout = 3600000000"

# ---------------------------------------------------------------------------
# 4. Accounts for HammerDB and the dashboard
# ---------------------------------------------------------------------------
seekdb_create_accounts

log "seekdb $(db_admin 'SELECT VERSION()') is running on port $SEEKDB_PORT, reachable from this node only (memory budget ${BUDGET_MB}MB, ${CPUS} CPUs)"
[[ $FRESH_INSTALL == 1 ]] && log "root credentials are in $MYSQL_ADMIN_CNF (linked from /root/.my.cnf)"
log "next step: $(dirname "$0")/database-generate.sh"
